import { PGlite } from "@electric-sql/pglite";
import { readFileSync } from "node:fs";
import assert from "node:assert/strict";
const db = new PGlite();
await db.exec("create role anon; create role authenticated; create role service_role; create schema auth; create table auth.users(id uuid primary key,email text,email_confirmed_at timestamptz,raw_user_meta_data jsonb default '{}'); create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;");
await db.exec(readFileSync("supabase/player-social.sql", "utf8"));
await db.exec(readFileSync("supabase/social-invitations.sql", "utf8"));
await db.exec(readFileSync("supabase/duo-predictions.sql", "utf8"));
await db.exec(readFileSync("supabase/duo-invitations.sql", "utf8"));
const owner=crypto.randomUUID(),friend=crypto.randomUUID(),outsider=crypto.randomUUID();
for(const [id,email] of [[owner,"owner@example.test"],[friend,"friend@example.test"],[outsider,"outside@example.test"]]) await db.query("insert into auth.users(id,email,email_confirmed_at) values($1,$2,now())",[id,email]);
const as=async(id,role="authenticated")=>{await db.exec("set role "+role);await db.query("select set_config('request.jwt.claim.sub',$1,false)",[id]);};
const rpc=async(name,args=[])=> (await db.query("select public."+name+"("+args.map((_,i)=>"$"+(i+1)).join(",")+") as data",args)).rows[0].data;
await as(owner);
await db.exec("reset role");
await db.query("insert into public.dilemma_friendships(user_a,user_b) values(least($1::uuid,$2::uuid),greatest($1::uuid,$2::uuid))",[owner,friend]);
await as(owner);
const code=await rpc("create_dilemma_duel_v2",[JSON.stringify(["a","b","c","d","e"]),JSON.stringify([0,1,0,1,0]),null,JSON.stringify([1,1,0,0,1])]);
const invite=await rpc("create_dilemma_duel_invitation",[code,friend,null]);
assert.equal(invite.recipientFound,true);
await as(friend);
const incoming=await rpc("list_dilemma_duos");
assert.equal(incoming[0].code,code);assert.equal(incoming[0].invited,true);
await as(outsider);assert.deepEqual(await rpc("list_dilemma_duos"),[]);
await as(owner,"service_role");
const mail=await rpc("claim_dilemma_duel_email",[invite.id,owner]);
assert.equal(mail.email,"friend@example.test");assert.equal(mail.code,code);
await db.close();
console.log("Duo invitations passed: friend validation, account notification, privacy and trusted email delivery.");
